#!/usr/bin/env bash
# PreToolUse フック（matcher: Edit|Write|MultiEdit）
# 生成コード・秘密情報・ロックファイルへの直接編集をブロックする。

set -u
input="$(cat)"

extract() {
  if command -v jq >/dev/null 2>&1; then
    printf '%s' "$input" | jq -r '.tool_input.file_path // empty'
  elif command -v python3 >/dev/null 2>&1; then
    printf '%s' "$input" | python3 -c 'import json,sys; print(json.load(sys.stdin).get("tool_input",{}).get("file_path",""))'
  else
    printf '%s' "$input" | sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p'
  fi
}
path="$(extract)"
[ -z "$path" ] && exit 0

DENY_PATHS=(
  '(^|/)generated/'
  '\.g\.dart$'
  '\.freezed\.dart$'
  '(^|/)\.env(\..*)?$'
  '(^|/)(id_rsa|id_ed25519)(\.pub)?$'
  '\.(pem|p12|keystore|jks|mobileprovision)$'
  '(^|/)(pnpm-lock\.yaml|package-lock\.json|yarn\.lock|go\.sum|pubspec\.lock|Package\.resolved|packages\.lock\.json)$'
  '\.xcodeproj/'
)

for pat in "${DENY_PATHS[@]}"; do
  if printf '%s' "$path" | grep -Eq -- "$pat"; then
    echo "BLOCKED by harness guard: '$path' matches '$pat'. Generated files are regenerated from their source; lock files are changed by the package manager; secrets are never written by the agent; .xcodeproj is generated by XcodeGen." >&2
    exit 2
  fi
done
exit 0

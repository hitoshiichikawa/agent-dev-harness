#!/usr/bin/env bash
# PreToolUse フック（matcher: Edit|Write|MultiEdit）
# 生成コード・秘密情報・ロックファイルへの直接編集をブロックする。
# 終了コード 2 = ブロック。0 = 許可。
# 0 と 2 以外は Claude Code では続行扱いなので、途中で落ちたら EXIT トラップで 2 に変える。

set -u
fail_closed() {
  local rc=$?
  if [ "$rc" -ne 0 ] && [ "$rc" -ne 2 ]; then
    echo "BLOCKED by harness guard: the guard script itself failed (exit $rc), so this edit was not checked. Do not work around it. Tell the user that .claude/hooks/common/guard-edit.sh is broken." >&2
    exit 2
  fi
}
trap fail_closed EXIT

input="$(cat)"
# Claude Code は必ず JSON を渡す。空なら配線の誤り（入力を別のスクリプトが先に読んだ等）なので止める
[ -n "$input" ] || exit 3

extract() {
  if command -v jq >/dev/null 2>&1; then
    printf '%s' "$input" | jq -r '.tool_input.file_path // empty'
  elif command -v python3 >/dev/null 2>&1; then
    printf '%s' "$input" | python3 -c 'import json,sys; print(json.load(sys.stdin).get("tool_input",{}).get("file_path",""))'
  else
    printf '%s' "$input" | sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p'
  fi
}
if ! path="$(extract)"; then exit 3; fi
[ -z "$path" ] && exit 0

ENV_PATTERN='(^|/)\.env(\..*)?$'
DENY_PATHS=(
  '(^|/)generated/'
  '\.g\.dart$'
  '\.freezed\.dart$'
  "$ENV_PATTERN"
  '(^|/)(id_rsa|id_ed25519)(\.pub)?$'
  '\.(pem|p12|keystore|jks|mobileprovision)$'
  '(^|/)(pnpm-lock\.yaml|package-lock\.json|yarn\.lock|go\.sum|pubspec\.lock|Package\.resolved|packages\.lock\.json)$'
  '\.xcodeproj/'
)

# プロジェクト固有の追加を読む（1 行 1 拡張正規表現。# で始まる行と空行は読み飛ばす）。
# 生成コードが generated/ 以外の場所にあるプロジェクト（後から導入した既存リポジトリなど）は、ここに足す。
# 読み方は guard-bash.sh の extra-deny.txt と同じ。現在のディレクトリには依存しない。
script_dir="$(cd "$(dirname "$0")" && pwd)"
for extra_file in "${CLAUDE_PROJECT_DIR:-}/.claude/hooks/extra-deny-paths.txt" "$script_dir/../extra-deny-paths.txt"; do
  [ -f "$extra_file" ] || continue
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    case "$line" in ''|'#'*) continue ;; esac
    DENY_PATHS+=("$line")
  done < "$extra_file"
  break
done

# .env.example は値を入れない見本で、秘密情報ではない。ローカル開発用の項目を足せるよう通す
is_env_example=0
[ "${path##*/}" = ".env.example" ] && is_env_example=1

for pat in "${DENY_PATHS[@]}"; do
  if [ "$pat" = "$ENV_PATTERN" ] && [ "$is_env_example" -eq 1 ]; then continue; fi
  printf '%s' "$path" | grep -Eq -- "$pat"
  rc=$?
  if [ "$rc" -eq 0 ]; then
    echo "BLOCKED by harness guard: '$path' matches '$pat'. Generated files are regenerated from their source; lock files are changed by the package manager; secrets are never written by the agent; .xcodeproj is generated by XcodeGen; paths listed in .claude/hooks/extra-deny-paths.txt are protected by this project." >&2
    exit 2
  elif [ "$rc" -ne 1 ]; then
    # 正規表現が壊れている。黙って読み飛ばすとそのパターンが効かなくなるので止める
    echo "harness guard: invalid deny path pattern '$pat' (grep exit $rc)" >&2
    exit 3
  fi
done
exit 0
